# t <clé> [arguments…] — rend la phrase traduite. Repli en chaîne :
# langue demandée -> en -> fr. Le repli est délibérément une PHRASE et non la
# clé : un affichage dégradé reste lisible, une clé technique ne l'est pas.
# Le français ferme la chaîne parce qu'il est la langue d'origine du catalogue.
t() {
    local cle="$1"; shift
    local fmt="${_T[${CALYPSO_LANG}:$cle]:-${_T[en:$cle]:-${_T[fr:$cle]:-$cle}}}"
    # shellcheck disable=SC2059
    printf "$fmt" "$@"
}

# t_mod <module> — la description traduite du module ; à défaut, celle que le
# module a déclarée lui-même dans MOD_REGISTER.
t_mod() {
    printf '%s' "${_TM[${CALYPSO_LANG}:$1]:-${_TM[en:$1]:-${_TM[fr:$1]:-${MOD_DESC[$1]:-$1}}}}"
}

# Langue inconnue : on le DIT et on retombe sur le français, plutôt que de
# laisser un affichage vide faire croire à une panne.
case " fr de en es pt it hi zh ar " in
    *" $CALYPSO_LANG "*) ;;
    *) printf 'CALYPSO_LANG=%s inconnue — repli sur « en » (fr de en es pt it hi zh ar)\n' \
              "$CALYPSO_LANG" >&2
       CALYPSO_LANG=en ;;
esac

