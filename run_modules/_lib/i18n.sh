# =============================================================================
#  _lib/i18n.sh — une seule langue pour tout l'affichage
# =============================================================================
#
#  POURQUOI  L'affichage mélangeait le français des modules et l'anglais des
#            outils. « CALYPSO_LANG » unifie : TOUT ce que le lanceur écrit sort
#            dans la langue choisie, et rien d'autre.
#
#      CALYPSO_LANG=en ./run.sh        ou        ./run.sh --lang en
#      ./run.sh --configure            (le choix devient permanent)
#
#  LANGUES   en (défaut) · fr · de · es · pt · it · hi · zh · ar
#
#  CE QUI EST TRADUIT
#    - les mots d'état et les phrases du moteur (ce qui défile à chaque ligne) ;
#    - la description de chaque module, c'est-à-dire le libellé de la ligne.
#    Le CORPS des messages d'un module (mod_say détaillé) reste dans sa langue
#    d'origine : le traduire demanderait de reprendre plusieurs centaines de
#    phrases, et une traduction partielle serait pire que pas de traduction.
#    Les journaux des programmes tiers (osmo-*, QEMU) ne sont pas concernés :
#    ce sont leurs sorties, pas les nôtres.
#
#  AJOUTER UNE LANGUE  ajoutez son code aux tableaux ci-dessous. Toute clé
#  absente retombe sur le français — jamais sur une chaîne vide.
# -----------------------------------------------------------------------------
: "${CALYPSO_LANG:=en}"

